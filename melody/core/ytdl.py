async def get_video_info(url_or_query: str) -> dict | None:
    """Get metadata for a single video (or first search result).

    KEY FIX for Heroku "Sign in to confirm you're not a bot":
    • Uses extract_flat=True — yt-dlp fetches only lightweight metadata
      (title, duration, uploader, thumbnail) WITHOUT requesting streamingData
      (the format/CDN URL list). streamingData calls are what trigger YouTube's
      bot-detection check on cloud IPs. By deferring stream resolution to
      download_audio(), we avoid the check entirely at this stage.
    • For direct YouTube URLs we extract the video_id and search by video_id,
      still via the flat/metadata path (no streamingData request).
    """
    import re
    is_url = bool(re.match(r"https?://", url_or_query))

    if is_url:
        vid_id = _extract_video_id(url_or_query)
        # Use ytsearch1: for the video URL — forces the search API path which
        # only fetches metadata, not streamingData.
        query = f"ytsearch1:{url_or_query}" if not vid_id else f"ytsearch1:https://www.youtube.com/watch?v={vid_id}"
    else:
        query = f"ytsearch1:{url_or_query}"
        vid_id = None

    def _info():
        # CRITICAL FIX: noplaylist=False is REQUIRED for ytsearch1: queries.
        # yt-dlp 2025+ internally wraps ytsearch results in a "SearchResultsPlaylist".
        # With noplaylist=True (from _ydl_opts), yt-dlp refuses to process it → returns
        # nothing → silent "Song not found" error even when the video exists.
        # extract_flat="in_playlist" — lightweight metadata only, no streamingData request
        # (streamingData = the CDN URL list that triggers YouTube bot-detection on Heroku).
        opts = {
            **_ydl_opts(),
            "extract_flat": "in_playlist",
            "default_search": "ytsearch1",
            "noplaylist": False,    # MUST be False for ytsearch1: to work
            "socket_timeout": 6,    # fail fast so Invidious fallback runs sooner
        }
        with YoutubeDL(opts) as ydl:
            info = ydl.extract_info(query, download=False)
            if info and "entries" in info and info["entries"]:
                return info["entries"][0]
            return info

    try:
        loop = asyncio.get_running_loop()
        info = await loop.run_in_executor(None, _info)
        if not info or not info.get("id"):
            # ── Invidious fallback: yt-dlp search returned nothing ──────────
            # On Heroku, YouTube's bot-detection sometimes blocks yt-dlp even
            # with Android/iOS clients. Invidious runs its own YouTube API proxy
            # on non-cloud IPs — it is not affected by Heroku's IP ban.
            LOGGER.info("yt-dlp search returned nothing — trying InnerTube fallback | %s", url_or_query[:50])
            info = await asyncio.get_event_loop().run_in_executor(
                None, _innertube_search_sync, url_or_query
            )
            if not info or not info.get("id"):
                LOGGER.info("InnerTube returned nothing — trying Invidious | %s", url_or_query[:50])
                info = await asyncio.get_event_loop().run_in_executor(
                    None, _invidious_search_sync, url_or_query
                )
            if not info or not info.get("id"):
                return None
        vid = info.get("id", "")
        return {
            "id": vid,
            "title": info.get("title", "Unknown"),
            "duration": int(info.get("duration") or 0),
            "url": info.get("webpage_url") or f"https://www.youtube.com/watch?v={vid}",
            "stream_url": "",  # resolved at play time by download_audio()
            "thumbnail": info.get("thumbnail") or f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg",
            "uploader": info.get("uploader") or info.get("channel") or "Unknown",
        }
    except Exception as exc:
        # ── Invidious fallback on exception ─────────────────────────────────
        LOGGER.warning("yt-dlp get_video_info raised exception — trying InnerTube: %s", exc)
        try:
            loop2 = asyncio.get_event_loop()
            info = await loop2.run_in_executor(None, _innertube_search_sync, url_or_query)
            if not info or not info.get("id"):
                info = await loop2.run_in_executor(None, _invidious_search_sync, url_or_query)
            if info and info.get("id"):
                vid = info["id"]
                return {
                    "id": vid,
                    "title": info.get("title", "Unknown"),
                    "duration": int(info.get("duration") or 0),
                    "url": info.get("webpage_url") or f"https://www.youtube.com/watch?v={vid}",
                    "stream_url": "",
                    "thumbnail": info.get("thumbnail") or f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg",
                    "uploader": info.get("uploader") or "Unknown",
                }
        except Exception:
            pass
        await send_error_log("get_video_info failed", exc)
        return None


# ─────────────────────────────────────────────────────────────────────────────
#  FIFO pipe streaming  (⚡ Instant play — music starts before full download)
# ─────────────────────────────────────────────────────────────────────────────

def _start_pipe_download(video_id: str, audio_only: bool = True) -> str:
    """Start yt-dlp writing audio to a FIFO named pipe in a daemon thread.
    Returns the pipe path IMMEDIATELY — yt-dlp runs in the background.

    HOW IT SAVES TIME:
    • PyTgCalls opens the FIFO path from MediaStream().
    • yt-dlp starts downloading fragments and writing bytes continuously.
    • ffmpeg inside PyTgCalls reads as bytes arrive — music starts playing
      within ~2-3 s without waiting for the full file to download.

    Falls back: callers catch OSError when mkfifo is unavailable.
    """
    tmpdir = tempfile.mkdtemp(prefix="melody_pipe_")
    pipe_path = os.path.join(tmpdir, "audio.webm")
    try:
        os.mkfifo(pipe_path)
    except OSError as err:
        shutil.rmtree(tmpdir, ignore_errors=True)
        raise OSError(
            f"FIFO not supported on this platform ({err}). "
            "Falling back to full file download."
        ) from err

    url = f"https://www.youtube.com/watch?v={video_id}"
    fmt = (
        # Broad selector — same rationale as _ydl_opts(): ext constraints
        # removed to avoid "Requested format is not available" crashes.
        "bestaudio/best"
        if audio_only
        else "best[height<=720][vcodec!=none][acodec!=none]/best[height<=720]/best"
    )

    # Build a self-contained Python script that writes audio to stdout.
    # Running as a subprocess subprocess inherits sys.path but is isolated,
    # which avoids blocking the asyncio event loop.
    #
    # STRICT COOKIE MODE (kept in sync with _ydl_opts()):
    # android/ios/tv_embedded clients ignore cookiefile entirely — only the
    # "web"/"mweb" client paths use the logged-in session. So when cookies
    # exist, "web" goes first and the UA matches a real desktop browser.
    has_cookies = os.path.exists(COOKIES_FILE)
    cookie_line = (
        f'    opts["cookiefile"] = {repr(COOKIES_FILE)}\n' if has_cookies else ""
    )
    player_client_list = (
        ["web", "mweb", "tv_embedded", "android_music", "ios", "android"]
        if has_cookies
        else ["android_music", "ios", "android", "tv_embedded", "mweb", "web"]
    )
    user_agent = (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
        if has_cookies
        else "Mozilla/5.0 (Linux; Android 13; SM-S908B) AppleWebKit/537.36 "
             "(KHTML, like Gecko) Chrome/112.0.0.0 Mobile Safari/537.36"
    )
    script = (
        "import sys, yt_dlp\n"
        "opts = {\n"
        f'    "format": {repr(fmt)},\n'
        '    "outtmpl": "-",\n'
        '    "quiet": True,\n'
        '    "no_warnings": True,\n'
        '    "noplaylist": True,\n'
        '    "geo_bypass": True,\n'
        '    "geo_bypass_country": "US",\n'
        '    "socket_timeout": 10,\n'
        '    "retries": 5,\n'
        '    "fragment_retries": 5,\n'
        '    "check_formats": False,\n'
        # Sequential fragments for continuous pipe flow (see _ydl_opts doc)
        '    "concurrent_fragment_downloads": 1,\n'
        '    "extractor_args": {\n'
        '        "youtube": {\n'
        f'            "player_client": {repr(player_client_list)},\n'
        '        }\n'
        '    },\n'
        '    "http_headers": {\n'
        f'        "User-Agent": {repr(user_agent)},\n'
        '        "Referer": "https://www.youtube.com/",\n'
        '    },\n'
        "}\n"
        + cookie_line
        + f"with yt_dlp.YoutubeDL(opts) as ydl:\n"
        + f"    ydl.download([{repr(url)}])\n"
    )
    cmd = [sys.executable, "-c", script]

    with _active_pipes_lock:
        _active_pipes.add(pipe_path)

    def _writer() -> None:
        proc = None
        fifo_fd = None
        slot_acquired = False
        try:
            slot_acquired = _pipe_slots.acquire(timeout=_PIPE_SLOT_TIMEOUT)
            if not slot_acquired:
                LOGGER.warning("Pipe concurrency limit reached; abandoning FIFO | %s", video_id)
                return

            proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)

            # Blocking open — waits until PyTgCalls opens the read end.
            # Uses a daemon sub-thread so we can enforce a timeout.
            open_evt = threading.Event()
            open_result: list = [None]

            def _blocking_open():
                try:
                    open_result[0] = os.open(pipe_path, os.O_WRONLY)
                except Exception as e:
                    open_result[0] = e
                finally:
                    open_evt.set()

            t = threading.Thread(target=_blocking_open, daemon=True, name="melody-fifo-opener")
            t.start()

            deadline = time.monotonic() + _PIPE_CONNECT_TIMEOUT
            while not open_evt.wait(timeout=0.3):
                if time.monotonic() >= deadline:
                    LOGGER.warning("FIFO reader did not connect in %.1fs | %s", _PIPE_CONNECT_TIMEOUT, video_id)
                    try:
                        dummy = os.open(pipe_path, os.O_RDONLY | os.O_NONBLOCK)
                        os.close(dummy)
                    except Exception:
                        pass
                    return

            if isinstance(open_result[0], Exception):
                raise open_result[0]
            fifo_fd = open_result[0]

            # Relay yt-dlp stdout → FIFO directly (webm/opus passthrough, no re-encode)
            with os.fdopen(fifo_fd, "wb") as fifo:
                fifo_fd = None  # fdopen owns the fd now
                while True:
                    chunk = proc.stdout.read(65536)
                    if not chunk:
                        break
                    try:
                        fifo.write(chunk)
                    except (BrokenPipeError, OSError):
                        break

        except Exception as e:
            LOGGER.debug("FIFO writer error for %s: %s", video_id, e)
        finally:
            if fifo_fd is not None:
                try:
                    os.close(fifo_fd)
                except Exception:
                    pass
            if proc is not None:
                try:
                    proc.kill()
                    proc.wait(timeout=3)
                except Exception:
                    pass
            if slot_acquired:
                _pipe_slots.release()
            with _active_pipes_lock:
                _active_pipes.discard(pipe_path)
            try:
                shutil.rmtree(tmpdir, ignore_errors=True)
            except Exception:
                pass

    threading.Thread(target=_writer, daemon=True, name=f"melody-pipe-{video_id[:8]}").start()
    return pipe_path


# ─────────────────────────────────────────────────────────────────────────────
#  Full file download (fallback for when FIFO is unavailable or pipe fails)
# ─────────────────────────────────────────────────────────────────────────────

def _download_audio_sync(video_id: str, audio_only: bool = True) -> str:
    """Synchronous full-file download — used as fallback when FIFO unavailable."""
    url = f"https://www.youtube.com/watch?v={video_id}"
    outtmpl = f"/tmp/melody_{video_id}.%(ext)s"
    opts = {
        **_ydl_opts(audio_only=audio_only),
        "outtmpl": outtmpl,
        "extract_flat": False,
    }
    with YoutubeDL(opts) as ydl:
        info = ydl.extract_info(url, download=True)
        filepath = ydl.prepare_filename(info)
    if not os.path.exists(filepath):
        found = glob.glob(f"/tmp/melody_{video_id}.*")
        if found:
            return found[0]
        raise FileNotFoundError(f"Downloaded file not found for video_id={video_id}")
    return filepath


async def download_audio(video_id: str, audio_only: bool = True) -> str:
    """Return a path to play audio from.

    Strategy: always do a full file download to /tmp, then hand the finished
    file's path to PyTgCalls.

    FIFO pipe streaming was REMOVED (root-cause fix): PyTgCalls' MediaStream
    always calls ffmpeg.check_stream() before playback, which runs `ffprobe`
    on the given path and reads it start-to-EOF to inspect the stream. A
    named pipe (FIFO) only supports being drained ONCE — after ffprobe
    finishes reading it for the probe, there is nothing left in the pipe for
    the real ffmpeg playback process that follows, and by then our writer
    thread has already deleted the tmp directory. This is exactly what was
    causing `_stream_track failed ... FileNotFoundError` / "No such file" in
    the logs: check_stream() drained (or outright missed, on a slow/slotted
    writer) the pipe before real playback could read anything from it.

    A one-shot FIFO simply cannot survive being read twice (probe + play),
    so the "instant streaming" pipe trick is fundamentally incompatible with
    this pytgcalls version and has to go. The bot still starts fast because
    the VC join (pre_join) and the download both run concurrently — only the
    download itself is no longer piped.

    Files written to /tmp/melody_<video_id>.* are cleaned up by call.py after
    each track finishes to avoid filling the 512 MB /tmp on Heroku.
    """
    # Cache check — reuse if already downloaded
    cached = glob.glob(f"/tmp/melody_{video_id}.*")
    if cached:
        return cached[0]

    loop = asyncio.get_running_loop()
    filepath = await loop.run_in_executor(None, _download_audio_sync, video_id, audio_only)
    return filepath


# ─────────────────────────────────────────────────────────────────────────────
#  Autoplay helpers
# ─────────────────────────────────────────────────────────────────────────────

async def get_related_videos(video_id: str, exclude_ids: list[str] = None) -> list[dict]:
    """Fetch related videos for autoplay (skip excluded IDs)."""
    exclude = set(exclude_ids or [])

    def _related():
        # ROOT-CAUSE FIX: this call only needs lightweight metadata (title,
        # duration, thumbnail) for the autoplay queue — it must never try to
        # resolve a playable *format* for anything. The previous version
        # reused _ydl_opts(), which always sets a strict "format" selector
        # for downloading. Even with extract_flat=True, yt-dlp still fully
        # processes the primary watch-page result before flattening the
        # "up next" mix, so an unavailable format on that primary video
        # (age-restricted, region-locked, or a format list YouTube changed)
        # raised straight out of extract_info() and killed the whole
        # autoplay lookup — that's the "Requested format is not available"
        # crash from the error log.
        #
        # Fix: request YouTube's dedicated "up next" Mix/Radio playlist
        # (list=RD<id>) so entries come back as flat playlist items (never
        # format-resolved), strip the format selector entirely, and ignore
        # per-entry errors so one broken related video can't blank the list.
        url = f"https://www.youtube.com/watch?v={video_id}&list=RD{video_id}"
        opts = {**_ydl_opts(), "extract_flat": True, "playlist_items": "1:10"}
        opts.pop("format", None)
        opts["ignoreerrors"] = True
        opts["skip_download"] = True
        with YoutubeDL(opts) as ydl:
            info = ydl.extract_info(url, download=False)
            return info.get("entries") or [] if info else []

    try:
        loop = asyncio.get_running_loop()
        entries = await loop.run_in_executor(None, _related)
        results = []
        for e in entries:
            if not e:
                continue  # ignoreerrors leaves a None slot for a broken entry
            vid = e.get("id", "")
            if vid and vid not in exclude:
                results.append({
                    "id": vid,
                    "title": e.get("title", "Unknown"),
                    "duration": e.get("duration", 0),
                    "url": f"https://www.youtube.com/watch?v={vid}",
                    "thumbnail": e.get("thumbnail") or f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg",
                    "uploader": e.get("uploader", "Unknown"),
                })
        return results
    except Exception as exc:
        await send_error_log("get_related_videos failed", exc)
        return []
