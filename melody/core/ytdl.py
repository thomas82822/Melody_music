def _ydl_opts(audio_only: bool = True) -> dict:
    """Return base yt-dlp options tuned for Heroku and bot-detection bypass.

    FIXES:
    • "Sign in to confirm you're not a bot":
        android_music → ios → android → tv_embedded → mweb → web
        Android/iOS clients are served a different API path that skips the
        sign-in wall for public videos.  This is the canonical yt-dlp fix.
    • WebM/Opus format preferred — streamable via FIFO pipe without seeking.
      AAC/M4A requires the moov atom at end-of-file → breaks pipe mode.
    • geo_bypass — Heroku USA servers sometimes hit geo-restricted content;
      bypass declaration helps with most non-DRM videos.
    • concurrent_fragment_downloads=1 — sequential fragments keep the FIFO
      data stream continuous; parallel downloads create write bursts → pipe
      starvation → ntgcalls EOF → Broken pipe.
    """
    fmt = (
        # Use broad selector — ext constraints removed since FIFO pipe was
        # removed; full file download supports any container.  YouTube
        # occasionally does not serve a specific ext (region/age restrictions),
        # causing "Requested format is not available".  bestaudio/best lets
        # yt-dlp pick whatever is actually available.
        "bestaudio/best"
        if audio_only
        else "best[height<=720][vcodec!=none][acodec!=none]/best[height<=720]/best"
    )
    has_cookies = os.path.exists(COOKIES_FILE)

    # STRICT COOKIE MODE:
    # android_music/ios/tv_embedded clients authenticate via their own
    # embedded API keys and IGNORE a cookiefile entirely — cookies only take
    # effect on the "web"/"mweb" client paths. So when cookies are present we
    # put "web" FIRST (uses the logged-in session, bypasses bot-detection and
    # age/sign-in walls) and keep the others only as a safety-net fallback.
    player_client = (
        ["web", "mweb", "tv_embedded", "android_music", "ios", "android"]
        if has_cookies
        else ["tv_embedded", "android_music", "ios", "android", "mweb", "web"]
    )
    # A cookies.txt file is exported from a real desktop/mobile browser
    # session — pairing it with a matching browser User-Agent (instead of the
    # generic mobile UA) keeps the request fingerprint consistent and avoids
    # extra bot-detection flags.
    user_agent = (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
        if has_cookies
        else "Mozilla/5.0 (Linux; Android 13; SM-S908B) AppleWebKit/537.36 "
             "(KHTML, like Gecko) Chrome/112.0.0.0 Mobile Safari/537.36"
    )

    opts: dict = {
        "quiet": True,
        "no_warnings": True,
        "noplaylist": True,
        "format": fmt,
        "postprocessors": [],
        "geo_bypass": True,
        "geo_bypass_country": "US",
        "socket_timeout": 10,
        "retries": 5,
        "fragment_retries": 5,
        "check_formats": False,
        "concurrent_fragment_downloads": 1,
        "extractor_args": {
            "youtube": {
                "player_client": player_client,
            }
        },
        "http_headers": {
            "User-Agent": user_agent,
            "Referer": "https://www.youtube.com/",
        },
    }
    # NOTE: curl_cffi "impersonate" intentionally removed.
    # The impersonate target varies by installed version and crashes yt-dlp
    # with "Impersonate target not available" on older curl_cffi builds.
    if has_cookies:
        opts["cookiefile"] = COOKIES_FILE
    if Config.YT_PROXY:
        opts["proxy"] = Config.YT_PROXY
    return opts


